#!/usr/bin/env python3
"""
LingoSync AI - Faster-Whisper CLI Transcriber
Transcribe any local audio or video file into SRT, VTT, or JSON subtitles.
"""

import sys
import os
import argparse
import json

try:
    from faster_whisper import WhisperModel
except ImportError:
    print("Error: faster-whisper is not installed. Run: pip install faster-whisper")
    sys.exit(1)


def format_srt_time(seconds: float) -> str:
    hrs = int(seconds // 3600)
    mins = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    millis = int((seconds % 1) * 1000)
    return f"{hrs:02d}:{mins:02d}:{secs:02d},{millis:03d}"


def format_vtt_time(seconds: float) -> str:
    return format_srt_time(seconds).replace(",", ".")


def main():
    parser = argparse.ArgumentParser(description="LingoSync AI Offline Transcriber")
    parser.add_argument("input_file", help="Path to video or audio file (MP4, MKV, MOV, MP3, WAV, etc.)")
    parser.add_argument("--output", "-o", help="Output file path (default: input_file.srt)")
    parser.add_argument("--format", "-f", choices=["srt", "vtt", "json"], default="srt", help="Output format")
    parser.add_argument("--model", "-m", default="base", choices=["tiny", "base", "small", "medium", "large-v3"], help="Model size")
    parser.add_argument("--language", "-l", default=None, help="Spoken language code (e.g. 'en', 'es', 'hi')")
    parser.add_argument("--device", "-d", default="cpu", choices=["cpu", "cuda"], help="Inference device")

    args = parser.parse_args()

    if not os.path.exists(args.input_file):
        print(f"Error: File not found: {args.input_file}")
        sys.exit(1)

    print(f"Loading faster-whisper model '{args.model}' on {args.device}...")
    model = WhisperModel(args.model, device=args.device, compute_type="int8")

    print(f"Transcribing '{args.input_file}' with word timestamps...")
    segments, info = model.transcribe(
        args.input_file,
        beam_size=5,
        word_timestamps=True,
        vad_filter=True,
        language=args.language,
    )

    print(f"Detected language: {info.language} (probability: {info.language_probability:.2f})")
    print(f"Duration: {info.duration:.1f}s")

    seg_list = list(segments)
    output_path = args.output or f"{os.path.splitext(args.input_file)[0]}.{args.format}"

    if args.format == "srt":
        with open(output_path, "w", encoding="utf-8") as f:
            for i, seg in enumerate(seg_list, start=1):
                f.write(f"{i}\n")
                f.write(f"{format_srt_time(seg.start)} --> {format_srt_time(seg.end)}\n")
                f.write(f"{seg.text.strip()}\n\n")

    elif args.format == "vtt":
        with open(output_path, "w", encoding="utf-8") as f:
            f.write("WEBVTT - Generated by LingoSync AI Faster-Whisper\n\n")
            for i, seg in enumerate(seg_list, start=1):
                f.write(f"{i}\n")
                f.write(f"{format_vtt_time(seg.start)} --> {format_vtt_time(seg.end)}\n")
                f.write(f"{seg.text.strip()}\n\n")

    elif args.format == "json":
        data = {
            "language": info.language,
            "duration": info.duration,
            "segments": [
                {
                    "id": i,
                    "start": seg.start,
                    "end": seg.end,
                    "text": seg.text.strip(),
                    "words": [
                        {"word": w.word.strip(), "start": w.start, "end": w.end}
                        for w in (seg.words or [])
                    ],
                }
                for i, seg in enumerate(seg_list, start=1)
            ],
        }
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

    print(f"\n[Success] Subtitles written to: {output_path}")


if __name__ == "__main__":
    main()

