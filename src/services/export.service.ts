import { Caption, SubtitleStyle, AspectRatio } from '../types';
import { SubtitleLayoutService } from './subtitleLayout.service';

export class ExportService {
  /**
   * Helper to format seconds into SRT timestamp: HH:MM:SS,mmm
   */
  static formatSRTTime(seconds: number): string {
    const pad = (n: number, z = 2) => ('00' + n).slice(-z);
    const hrs = Math.floor(seconds / 3600);
    const mins = Math.floor((seconds % 3600) / 60);
    const secs = Math.floor(seconds % 60);
    const millis = Math.floor((seconds % 1) * 1000);
    return `${pad(hrs)}:${pad(mins)}:${pad(secs)},${pad(millis, 3)}`;
  }

  /**
   * Helper to format seconds into VTT timestamp: HH:MM:SS.mmm
   */
  static formatVTTTime(seconds: number): string {
    return this.formatSRTTime(seconds).replace(',', '.');
  }

  /**
   * Helper to format seconds into ASS timestamp: H:MM:SS.cc (centiseconds)
   */
  static formatASSTime(seconds: number): string {
    const pad = (n: number, z = 2) => ('00' + n).slice(-z);
    const hrs = Math.floor(seconds / 3600);
    const mins = Math.floor((seconds % 3600) / 60);
    const secs = Math.floor(seconds % 60);
    const centis = Math.floor((seconds % 1) * 100);
    return `${hrs}:${pad(mins)}:${pad(secs)}.${pad(centis, 2)}`;
  }

  /**
   * Converts Hex Color (#RRGGBB or #RGB) to ASS &HAABBGGRR& format
   */
  private static hexToASSColor(hex: string, alphaHex = '00'): string {
    let clean = hex.replace('#', '').trim();
    if (clean.length === 3) {
      clean = clean.split('').map((c) => c + c).join('');
    }
    if (clean.length !== 6) {
      return '&H00FFFFFF&';
    }
    const r = clean.slice(0, 2);
    const g = clean.slice(2, 4);
    const b = clean.slice(4, 6);
    return `&H${alphaHex}${b}${g}${r}&`.toUpperCase();
  }

  /**
   * Generate SRT string from captions
   */
  static generateSRT(captions: Caption[]): string {
    return captions
      .map((c, i) => {
        return `${i + 1}\n${this.formatSRTTime(c.start)} --> ${this.formatSRTTime(
          c.end
        )}\n${c.text.trim()}\n`;
      })
      .join('\n');
  }

  /**
   * Generate VTT string from captions
   */
  static generateVTT(captions: Caption[]): string {
    const header = 'WEBVTT - Generated by LingoSync AI\n\n';
    const body = captions
      .map((c, i) => {
        return `${i + 1}\n${this.formatVTTTime(c.start)} --> ${this.formatVTTTime(
          c.end
        )}\n${c.text.trim()}\n`;
      })
      .join('\n');
    return header + body;
  }

  /**
   * Generate ASS (Advanced SubStation Alpha) with full styling tags
   */
  static generateASS(
    captions: Caption[],
    style: SubtitleStyle,
    aspectRatio: AspectRatio = '16:9'
  ): string {
    let resX = 1920;
    let resY = 1080;
    if (aspectRatio === '9:16') {
      resX = 1080;
      resY = 1920;
    } else if (aspectRatio === '1:1') {
      resX = 1080;
      resY = 1080;
    } else if (aspectRatio === '4:5') {
      resX = 1080;
      resY = 1350;
    }

    const primaryColor = this.hexToASSColor(style.color || '#FFFFFF');
    const outlineColor = this.hexToASSColor(
      style.strokeColor === 'transparent' ? '#000000' : style.strokeColor || '#000000'
    );
    const shadowColor = '&H80000000&';

    // Alignment: 2 = bottom-center, 8 = top-center, 5 = middle-center
    const alignment = style.position === 'top' ? 8 : style.position === 'center' ? 5 : 2;
    const marginV = Math.round(resY * ((style.yOffset || 10) / 100));

    let ass = `[Script Info]
; Script generated by LingoSync AI
Title: LingoSync Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: None
PlayResX: ${resX}
PlayResY: ${resY}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,${style.fontFamily},${Math.round(style.fontSize * (resY / 720))},${primaryColor},&H000000FF&,${outlineColor},${shadowColor},${
      style.fontWeight === '900' || style.fontWeight === '700' ? -1 : 0
    },0,0,0,100,100,${style.letterSpacing || 0},0,1,${style.strokeWidth || 2},${
      style.shadowBlur > 0 ? 2 : 0
    },${alignment},40,40,${marginV},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

    captions.forEach((c) => {
      // Convert newlines to ASS \N tag
      const formattedText = c.text.replace(/\n/g, '\\N');
      ass += `Dialogue: 0,${this.formatASSTime(c.start)},${this.formatASSTime(
        c.end
      )},Default,,0,0,0,,${formattedText}\n`;
    });

    return ass;
  }

  /**
   * Generate Plain Text transcript
   */
  static generateTXT(captions: Caption[]): string {
    return captions.map((c) => c.text.trim()).join('\n\n');
  }

  /**
   * Triggers a browser download of text content as a file
   */
  static downloadFile(content: string, filename: string, mimeType: string): void {
    const blob = new Blob([content], { type: `${mimeType};charset=utf-8;` });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    setTimeout(() => URL.revokeObjectURL(url), 2000);
  }

  static downloadSRT(captions: Caption[], filename = 'subtitles.srt'): void {
    const content = this.generateSRT(captions);
    this.downloadFile(content, filename, 'text/plain');
  }

  static downloadVTT(captions: Caption[], filename = 'subtitles.vtt'): void {
    const content = this.generateVTT(captions);
    this.downloadFile(content, filename, 'text/vtt');
  }

  static downloadASS(
    captions: Caption[],
    style: SubtitleStyle,
    filename = 'subtitles.ass',
    aspectRatio: AspectRatio = '16:9'
  ): void {
    const content = this.generateASS(captions, style, aspectRatio);
    this.downloadFile(content, filename, 'text/plain');
  }

  static downloadTXT(captions: Caption[], filename = 'transcript.txt'): void {
    const content = this.generateTXT(captions);
    this.downloadFile(content, filename, 'text/plain');
  }

  /**
   * Render and export video with burned-in subtitles using Canvas 2D + MediaRecorder.
   * Powered by the shared SubtitleLayoutService to guarantee preview-to-export parity.
   */
  static async exportBurnedInVideo(
    videoElement: HTMLVideoElement,
    captions: Caption[],
    style: SubtitleStyle,
    onProgress: (percent: number, status: string) => void,
    outputFilename = 'lingosync-captioned-video.webm',
    aspectRatio: AspectRatio = '16:9'
  ): Promise<void> {
    return new Promise(async (resolve, reject) => {
      try {
        if (!videoElement.duration || videoElement.duration === 0) {
          throw new Error('Video duration is invalid or video has not loaded.');
        }

        // Determine exact canvas output dimensions matching target aspect ratio
        let width = 1280;
        let height = 720;

        if (aspectRatio === '9:16') {
          width = 720;
          height = 1280;
        } else if (aspectRatio === '1:1') {
          width = 1080;
          height = 1080;
        } else if (aspectRatio === '4:5') {
          width = 1080;
          height = 1350;
        } else if (aspectRatio === 'custom') {
          width = videoElement.videoWidth || 1280;
          height = videoElement.videoHeight || 720;
        } else {
          // 16:9 Landscape
          width = 1280;
          height = 720;
        }

        const duration = videoElement.duration;
        const canvas = document.createElement('canvas');
        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext('2d', { alpha: false });

        if (!ctx) {
          throw new Error('Could not initialize canvas context');
        }

        // Setup audio stream capture
        const canvasStream = canvas.captureStream(30);
        let combinedStream = canvasStream;

        try {
          const videoStream = (videoElement as any).captureStream
            ? (videoElement as any).captureStream()
            : (videoElement as any).mozCaptureStream
            ? (videoElement as any).mozCaptureStream()
            : null;

          if (videoStream && videoStream.getAudioTracks().length > 0) {
            videoStream.getAudioTracks().forEach((track: MediaStreamTrack) => {
              combinedStream.addTrack(track);
            });
          }
        } catch (e) {
          console.warn('Could not capture audio track from video:', e);
        }

        const mimeType = MediaRecorder.isTypeSupported('video/webm;codecs=vp9,opus')
          ? 'video/webm;codecs=vp9,opus'
          : MediaRecorder.isTypeSupported('video/webm;codecs=vp8,opus')
          ? 'video/webm;codecs=vp8,opus'
          : 'video/webm';

        const recorder = new MediaRecorder(combinedStream, {
          mimeType,
          videoBitsPerSecond: 4500000,
        });

        const chunks: Blob[] = [];
        recorder.ondataavailable = (e) => {
          if (e.data.size > 0) chunks.push(e.data);
        };

        recorder.onstop = () => {
          const blob = new Blob(chunks, { type: mimeType });
          const url = URL.createObjectURL(blob);
          const a = document.createElement('a');
          a.href = url;
          a.download = outputFilename;
          document.body.appendChild(a);
          a.click();
          document.body.removeChild(a);
          setTimeout(() => URL.revokeObjectURL(url), 4000);
          onProgress(100, 'Export complete!');
          resolve();
        };

        // Prepare video playback for recording
        const prevMuted = videoElement.muted;
        const prevCurrentTime = videoElement.currentTime;
        videoElement.muted = true;
        videoElement.currentTime = 0;

        await new Promise((r) => {
          videoElement.onseeked = () => r(null);
        });

        recorder.start(250);
        await videoElement.play();

        let animFrameId: number;

        const renderFrame = () => {
          const time = videoElement.currentTime;
          const pct = Math.min(99, Math.round((time / duration) * 100));
          onProgress(pct, `Rendering video frames (${pct}%)...`);

          // 1. Fill background with sleek dark fill
          ctx.fillStyle = '#050506';
          ctx.fillRect(0, 0, width, height);

          // 2. Calculate aspect-ratio fit dimensions (prevent stretching or distortion)
          const videoAspect = (videoElement.videoWidth || 16) / (videoElement.videoHeight || 9);
          const targetAspect = width / height;

          let drawW = width;
          let drawH = height;
          let drawX = 0;
          let drawY = 0;

          if (videoAspect > targetAspect) {
            // Video is wider than canvas -> fit width, letterbox top/bottom
            drawH = Math.round(width / videoAspect);
            drawY = Math.round((height - drawH) / 2);
          } else {
            // Video is taller than canvas -> fit height, pillarbox left/right
            drawW = Math.round(height * videoAspect);
            drawX = Math.round((width - drawW) / 2);
          }

          // 3. Draw base video frame
          ctx.drawImage(videoElement, drawX, drawY, drawW, drawH);

          // 4. Render active subtitle using shared layout engine
          const activeCaption = captions.find((c) => time >= c.start && time <= c.end);
          if (activeCaption) {
            this.renderLayoutOnCanvas(ctx, activeCaption.text, style, width, height, aspectRatio);
          }

          if (!videoElement.paused && !videoElement.ended) {
            animFrameId = requestAnimationFrame(renderFrame);
          } else if (videoElement.ended || time >= duration - 0.2) {
            cancelAnimationFrame(animFrameId);
            onProgress(100, 'Finalizing video file...');
            recorder.stop();
            videoElement.muted = prevMuted;
            videoElement.currentTime = prevCurrentTime;
          }
        };

        animFrameId = requestAnimationFrame(renderFrame);

        videoElement.onended = () => {
          cancelAnimationFrame(animFrameId);
          if (recorder.state === 'recording') {
            recorder.stop();
          }
        };
      } catch (err: any) {
        onProgress(0, 'Export failed');
        reject(err);
      }
    });
  }

  /**
   * Draws multi-line styled subtitles on 2D canvas according to computed layout
   */
  private static renderLayoutOnCanvas(
    ctx: CanvasRenderingContext2D,
    text: string,
    style: SubtitleStyle,
    canvasWidth: number,
    canvasHeight: number,
    aspectRatio: AspectRatio
  ): void {
    const layout = SubtitleLayoutService.computeLayout({
      text,
      viewportWidth: canvasWidth,
      viewportHeight: canvasHeight,
      style,
      aspectRatio,
    });

    const { lines, fontSize, lineHeight, x, y, boxWidth, boxHeight, boxX, boxY } = layout;

    // 1. Draw unified background box around multiline text
    if (style.backgroundColor && style.backgroundColor !== 'transparent') {
      ctx.save();
      ctx.fillStyle = style.backgroundColor;
      const radius = style.backgroundRadius * layout.scaleFactor;

      if (ctx.roundRect) {
        ctx.beginPath();
        ctx.roundRect(boxX, boxY, boxWidth, boxHeight, radius);
        ctx.fill();
      } else {
        ctx.fillRect(boxX, boxY, boxWidth, boxHeight);
      }
      ctx.restore();
    }

    // 2. Set font typography
    ctx.save();
    ctx.font = `${style.fontWeight} ${fontSize}px "${style.fontFamily}", sans-serif`;
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';

    // 3. Render each wrapped line centered
    lines.forEach((line, index) => {
      const lineY = y + index * lineHeight;

      // Draw drop shadow if configured
      if (style.shadowBlur > 0) {
        ctx.save();
        ctx.shadowColor = style.shadowColor;
        ctx.shadowBlur = style.shadowBlur * layout.scaleFactor;
        ctx.shadowOffsetX = 0;
        ctx.shadowOffsetY = style.shadowOffsetY * layout.scaleFactor;
        ctx.fillStyle = style.color;
        ctx.fillText(line, x, lineY);
        ctx.restore();
      }

      // Draw stroke outline if configured
      if (style.strokeWidth > 0 && style.strokeColor !== 'transparent') {
        ctx.save();
        ctx.strokeStyle = style.strokeColor;
        ctx.lineWidth = style.strokeWidth * 2 * layout.scaleFactor;
        ctx.lineJoin = 'round';
        ctx.miterLimit = 2;
        ctx.strokeText(line, x, lineY);
        ctx.restore();
      }

      // Fill main text
      ctx.fillStyle = style.color;
      ctx.fillText(line, x, lineY);
    });

    ctx.restore();
  }
}
